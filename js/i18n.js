let currentLang = 'en';

const LANG_DISPLAY_NAMES = {
  cs: 'CZ',
  en: 'EN',
  pl: 'PL',
  sk: 'SK',
  de: 'DE',
  fr: 'FR',
  es: 'ES',
  zh: 'ZH', 
  ja: 'JA'  
};

function populateLanguageDropdown() {
  const select = document.getElementById('lang-select') || document.getElementById('lang-btn');
  if (!select || select.tagName !== 'SELECT') return;

  const availableLangs = Object.keys(I18N);
  select.innerHTML = '';
  availableLangs.forEach(lang => {
    const opt = document.createElement('option');
    opt.value = lang;
    opt.textContent = LANG_DISPLAY_NAMES[lang.toLowerCase()] || lang.toUpperCase();
    select.appendChild(opt);
  });
}

function t(key, params) {
  const dict = I18N[currentLang] || I18N['cs'] || {};
  let str = dict[key] !== undefined ? dict[key] : ((I18N['cs'] && I18N['cs'][key]) !== undefined ? I18N['cs'][key] : key);
  if (params && typeof params === 'object') {
    for (const k in params) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    }
  }
  return str;
}

function setLanguage(lang) {
  if (!I18N[lang]) lang = Object.keys(I18N)[0] || 'cs';
  currentLang = lang;
  try {
    localStorage.setItem('pki_lang', lang);
  } catch (e) {}

  document.documentElement.lang = lang;

  // Sync dropdown selected value with currentLang
  const select = document.getElementById('lang-select') || document.getElementById('lang-btn');
  if (select && select.tagName === 'SELECT') {
    if (select.options.length === 0) {
      populateLanguageDropdown();
    }
    select.value = lang;
  }

  const csOpt = document.getElementById('lang-opt-cs');
  const enOpt = document.getElementById('lang-opt-en');
  if (csOpt && enOpt) {
    if (lang === 'cs') {
      csOpt.classList.add('active');
      enOpt.classList.remove('active');
    } else {
      csOpt.classList.remove('active');
      enOpt.classList.add('active');
    }
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val !== undefined) {
      if (val.includes('<') && val.includes('>')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val !== undefined) el.placeholder = val;
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val !== undefined) el.title = val;
  });

  if (typeof updateCaSelects === 'function') updateCaSelects();
  if (typeof renderKeyring === 'function') renderKeyring();
  const activePanel = document.querySelector('.panel.active');
  if (activePanel && activePanel.id === 'panel-graph') {
    if (typeof renderGraph === 'function') renderGraph();
  }
  if (activePanel && activePanel.id === 'panel-decoder') {
    const resultBox = document.getElementById('dec-result');
    if (resultBox && resultBox.style.display !== 'none') {
      if (typeof decodePem === 'function') decodePem();
    }
  }
}

function changeLanguage(event) {
  let val = '';
  if (event && event.target && event.target.value) {
    val = event.target.value;
  } else if (typeof event === 'string') {
    val = event;
  } else {
    const select = document.getElementById('lang-select') || document.getElementById('lang-btn');
    if (select) val = select.value;
  }
  if (val) {
    setLanguage(val);
  }
}

function toggleLanguage() {
  const availableLangs = Object.keys(I18N);
  if (!availableLangs.length) return;
  const nextIdx = (availableLangs.indexOf(currentLang) + 1) % availableLangs.length;
  setLanguage(availableLangs[nextIdx]);
}

function initLanguage() {
  populateLanguageDropdown();

  let savedLang = 'en';
  try {
    savedLang = localStorage.getItem('pki_lang') || 'en';
  } catch (e) {}

  if (!I18N[savedLang]) {
    savedLang = Object.keys(I18N)[0] || 'en';
  }

  setLanguage(savedLang);
}
